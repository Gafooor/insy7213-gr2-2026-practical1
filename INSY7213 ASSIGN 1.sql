CREATE TABLE CUSTOMER (
      CUSTOMER_ID NUMBER(5) PRIMARY
KEY,
FIRST_NAME VARCHAR2(50),
SURNAME VARCHAR2(50),
ADDRESS VARCHAR2(100),
PHONE_NUM VARCHAR2(20),
EMAIL VARCHAR2(100)
);

CREATE TABLE STAFF (
STAFF_ID NUMBER(5) PRIMARY KEY,
FIRST_NAME VARCHAR2(50),
SURNAME VARCHAR2(50),
POSITION VARCHAR2(50),
PHONE_NUM VARCHAR2(20),
ADDRESS VARCHAR2(100),
EMAIL VARCHAR2(100)
);

CREATE TABLE VEHICLE (
VIN_NUMBER VARCHAR2(20) PRIMARY KEY,
VEHICLE_TYPE VARCHAR2(100),
MILEAGE NUMBER(10),
COLOUR VARCHAR2(30),
MANUFACTURER VARCHAR2(50)
);

CREATE TABLE DRIVER (
DRIVER_ID NUMBER(5) PRIMARY KEY,
FIRST_NAME VARCHAR2(50),
SURNAME VARCHAR2(50),
DRIVER_CODE VARCHAR2(10),
PHONE_NUM VARCHAR2(20),
ADDRESS VARCHAR2(100)
);

CREATE TABLE DELIVERY_ITEM (
DELIVERY_ITEM_ID NUMBER(5) PRIMARY KEY,
DESCRIPTION VARCHAR2(150),
STAFF_ID NUMBER(5),
CONSTRAINT FK_DELIVERY_STAFF
FOREIGN KEY (STAFF_ID)
REFERENCES STAFF(STAFF_ID)
);

CREATE TABLE BILLING (
BILL_ID NUMBER(5) PRIMARY KEY,
CUSTOMER_ID NUMBER(5),
STAFF_ID NUMBER(5),
BILL_DATE DATE,
CONSTRAINT FK_BILL_CUSTOMER
FOREIGN KEY (CUSTOMER_ID)
REFERENCES
CUSTOMER(CUSTOMER_ID),
CONSTRAINT FK_BILL_STAFF
FOREIGN KEY (STAFF_ID)
REFERENCES STAFF(STAFF_ID)
);

CREATE TABLE DRIVER_DELIVERIES (
DRIVER_DELIVERY_ID NUMBER(5) PRIMARY KEY,
VIN_NUMBER VARCHAR2(20),
DRIVER_ID NUMBER(5),
DELIVERY_ITEM_ID NUMBER(5),
CONSTRAINT FK_DD_VEHICLE
FOREIGN KEY (VIN_NUMBER)
REFERENCES
VEHICLE(VIN_NUMBER),
CONSTRAINT FK_DD_DRIVER
FOREIGN KEY (DRIVER_ID)
REFERENCES DRIVER(DRIVER_ID),
CONSTRAINT FK_DD_DELIVERY
FOREIGN KEY
(DELIVERY_ITEM_ID)
REFERENCES
DELIVERY_ITEM(DELIVERY_ITEM_ID)
);

